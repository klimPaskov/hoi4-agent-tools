/**
 * Player words for script words.
 *
 * Modders describe a task in the words the game shows them: a "national spirit" is an idea
 * in script, and "at war" is `has_war`. A query that uses the player words also searches for
 * the script word at reduced weight, so documentation that only uses the script word can
 * still answer. See ADR 0075.
 */
export interface VocabularyEntry {
  /** One or more consecutive words a player uses, matched after suffix folding. */
  player: string;
  /** The script word or command name the documentation uses instead. */
  script: string;
}

