/**
 * Turn campaign results into the committed reliability table (request ZR-4).
 *
 * Usage: tsx scripts/map-campaign/summarize.ts --store <dir> [--manifest <file>] [--out <file>]
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { manifestSchema } from './manifest.js';

interface Step {
  status: string;
  code: string;
  milliseconds: number;
  blockers: string[];
  errors: string[];
  warnings: Record<string, number>;
  failedChecks: string[];
}

interface Result {
  crash?: string;
  preview?: Step;
  write?: Step;
  inspect?: Step;
  files?: Record<string, number | boolean>;
  milliseconds?: number;
  peakRssMiB?: number;
  passed?: boolean;
}

function option(name: string): string | undefined {
  const index = process.argv.indexOf(name);
  return index < 0 ? undefined : process.argv[index + 1];
}

function cell(value: string): string {
  return value.replace(/\|/gu, '/').replace(/\s+/gu, ' ').slice(0, 160);
}

function outcome(result: Result | undefined): { outcome: string; defect: string } {
  if (result === undefined) return { outcome: 'not run', defect: '' };
  if (result.crash !== undefined) return { outcome: 'crash', defect: result.crash };
  for (const [name, step] of [
    ['preview', result.preview],
    ['write', result.write],
    ['inspect', result.inspect],
  ] as const) {
    if (step === undefined) continue;
    if (step.status !== 'ok') {
      return {
        outcome: `${name} refused`,
        defect: step.blockers[0] ?? step.errors[0] ?? step.code,
      };
    }
    if (step.failedChecks.length > 0)
      return { outcome: `${name} check failed`, defect: step.failedChecks[0]! };
  }
  const files = result.files ?? {};
  const problems = [
    files.contiguousIds === false ? 'province ids not contiguous' : '',
    Number(files.landBelowWater ?? 0) > 0 ? `${files.landBelowWater} land px below water` : '',
    Number(files.waterAboveSurface ?? 0) > 0
      ? `${files.waterAboveSurface} water px above surface`
      : '',
    Number(files.pixelsWithoutDefinition ?? 0) > 0
      ? `${files.pixelsWithoutDefinition} px without definition`
      : '',
    files.heightmapSameSize === false ? 'heightmap size differs' : '',
  ].filter((problem) => problem.length > 0);
  if (problems.length > 0) return { outcome: 'files wrong', defect: problems.join('; ') };
  return { outcome: 'pass', defect: '' };
}

async function main(): Promise<void> {
  const store = option('--store');
  if (store === undefined) throw new Error('--store is required');
  const manifestPath = path.resolve(
    option('--manifest') ?? 'docs/plans/map-campaign/manifest.json',
  );
  const out = path.resolve(option('--out') ?? 'docs/plans/map-campaign/results.md');
  const manifest = manifestSchema.parse(JSON.parse(await readFile(manifestPath, 'utf8')));
  const rows: string[] = [];
  const counts = new Map<string, number>();
  const times: number[] = [];
  const memory: number[] = [];
  for (const [index, entry] of manifest.maps.entries()) {
    const result = await readFile(path.join(store, 'results', `${entry.id}.json`), 'utf8')
      .then((text) => JSON.parse(text) as Result)
      .catch(() => undefined);
    const { outcome: verdict, defect } = outcome(result);
    counts.set(verdict, (counts.get(verdict) ?? 0) + 1);
    if (result?.milliseconds !== undefined && result.crash === undefined)
      times.push(result.milliseconds);
    if (result?.peakRssMiB !== undefined) memory.push(result.peakRssMiB);
    const provinces = result?.files?.provinces;
    rows.push(
      `| ${index + 1} | [${cell(entry.title)}](${entry.page}) | ${cell(entry.licence)} | ${entry.width} x ${entry.height} | ${entry.category} | ${verdict} | ${provinces ?? ''} | ${result?.milliseconds === undefined ? '' : Math.round(result.milliseconds / 1000)} | ${result?.peakRssMiB ?? ''} | ${cell(defect)} |`,
    );
  }
  const sorted = (values: number[]) => [...values].sort((left, right) => left - right);
  const median = (values: number[]) =>
    values.length === 0 ? 0 : sorted(values)[Math.floor(values.length / 2)]!;
  const summary = [...counts.entries()]
    .sort(([left], [right]) => (left < right ? -1 : 1))
    .map(([verdict, count]) => `${verdict}: ${count}`)
    .join(', ');
  const text = `# Map import reliability campaign: results

Generated by \`scripts/map-campaign/summarize.ts\` from the campaign results (request ZR-4 in [zin-requests.md](../zin-requests.md)). Images come from Wikimedia Commons under the listed licences and are not in the repository; [manifest.json](manifest.json) records each source, author, licence and SHA-256.

Each map runs \`hoi4.map_rewrite\` \`create_world\` with only \`reference.imagePath\` (preview, then write) in a fresh test mod over the installed game, then \`hoi4.map_inspect\`, then file checks: contiguous province ids, every map pixel defined, land above and water below the water surface (height 95), heightmap size.

Summary: ${summary}. Median time ${Math.round(median(times) / 1000)} s per map (preview, write and inspect), median peak memory ${median(memory)} MiB, highest ${Math.max(0, ...memory)} MiB.

| # | Map | Licence | Size | Category | Outcome | Provinces | Seconds | Peak MiB | Defect |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`;
  await writeFile(out, text);
  process.stdout.write(`${summary}\n`);
}

await main();
