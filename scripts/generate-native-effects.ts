import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { parseArgs } from 'node:util';

/**
 * Regenerates the fallback list of native effects (src/hoi4_agent_tools/focus/native-effects.ts)
 * from an installed game's documentation/effects_documentation.md. Project tooling.
 *
 *   tsx scripts/generate-native-effects.ts --game <game folder>            # rewrite the list
 *   tsx scripts/generate-native-effects.ts --game <game folder> --check    # exit 1 on drift
 *   tsx scripts/generate-native-effects.ts --game <game folder> --out f.ts # write elsewhere
 */

const target = path.resolve(
  import.meta.dirname,
  '..',
  'src',
  'hoi4_agent_tools',
  'focus',
  'native-effects.ts',
);

/** Effect names in the order the documentation lists their sections. */
export function documentedEffects(markdown: string): string[] {
  const names = new Set<string>();
  for (const match of markdown.matchAll(/^##\s+([a-z_][a-z0-9_]*)\s*$/gmu)) names.add(match[1]!);
  return [...names].sort();
}

export function renderNativeEffects(names: readonly string[], build: string): string {
  return [
    '/**',
    ' * Native effect identifiers used to distinguish direct scripted-effect calls',
    ' * from engine effects while importing focus completion rewards.',
    ' *',
    ` * Generated by scripts/generate-native-effects.ts from the HOI4 ${build} effects`,
    ' * documentation. This is the fallback list; analysis also accepts every effect the installed',
    ' * game documents in documentation/effects_documentation.md, so effects added by later patches',
    ' * are recognized. The nightly game-update watcher regenerates it for review on a new build.',
    ' */',
    'export const nativeEffectKeys: ReadonlySet<string> = new Set([',
    ...names.map((name) => `  '${name}',`),
    ']);',
    '',
  ].join('\n');
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: {
      game: { type: 'string' },
      out: { type: 'string' },
      check: { type: 'boolean', default: false },
    },
  });
  if (values.game === undefined) {
    process.stderr.write('Pass --game <game folder>\n');
    process.exit(2);
  }
  const markdown = await readFile(
    path.join(values.game, 'documentation', 'effects_documentation.md'),
    'utf8',
  );
  const settings = JSON.parse(
    await readFile(path.join(values.game, 'launcher-settings.json'), 'utf8'),
  ) as { rawVersion?: string };
  const rendered = renderNativeEffects(
    documentedEffects(markdown),
    settings.rawVersion ?? 'unknown',
  );
  const output = values.out === undefined ? target : path.resolve(values.out);
  if (values.check) {
    const current = await readFile(target, 'utf8');
    if (current !== rendered) {
      process.stderr.write(`${target} differs from the installed game's documentation\n`);
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(output, rendered);
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === import.meta.filename)
  await main();
